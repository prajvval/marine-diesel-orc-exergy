def fig01_energy_balance():
    df = pd.read_csv(os.path.join(RES, '01_engine_energy_balance.csv'))
    loads = df['Load_pct']

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 4.5))
    fig.subplots_adjust(wspace=0.35)

    # --- Panel (a): stacked energy fractions ---
    ax1.fill_between(loads, 0, df['W_brake_pct'],
                     color='#009988', alpha=0.75, label='Shaft work')
    ax1.fill_between(loads,
                     df['W_brake_pct'],
                     df['W_brake_pct'] + df['Q_exhaust_pct'],
                     color='#CC3311', alpha=0.75, label='Exhaust heat')
    ax1.fill_between(loads,
                     df['W_brake_pct'] + df['Q_exhaust_pct'],
                     df['W_brake_pct'] + df['Q_exhaust_pct'] + df['Q_charge_air_pct'],
                     color='#0077BB', alpha=0.65, label='Charge-air cooling')
    ax1.fill_between(loads,
                     df['W_brake_pct'] + df['Q_exhaust_pct'] + df['Q_charge_air_pct'],
                     df['W_brake_pct'] + df['Q_exhaust_pct'] + df['Q_charge_air_pct'] + df['Q_jacket_pct'],
                     color='#EE7733', alpha=0.65, label='Jacket water')

    ax1.set_xlim(20, 100)
    ax1.set_ylim(0, 105)
    ax1.set_xlabel('Engine load (% MCR)')
    ax1.set_ylabel('Energy fraction (%)')
    ax1.legend(loc='lower right', fontsize=8)
    _panel_label(ax1, '(a)')

    # --- Panel (b): brake efficiency + BSFC ---
    color_eta  = '#1A1A1A'
    color_bsfc = '#555555'
    ax2b = ax2.twinx()
    lns1, = ax2.plot(loads, df['eta_brake'] * 100, color=color_eta,
                     lw=1.8, label=r'$\eta_\mathrm{BT}$ (%)')
    lns2, = ax2b.plot(loads, df['BSFC_g_kWh'], color=color_bsfc,
                      lw=1.0, ls='--', label='BSFC (g/kWh)')

    ax2.set_xlim(20, 100)
    ax2.set_xlabel('Engine load (% MCR)')
    ax2.set_ylabel(r'Brake thermal efficiency $\eta_\mathrm{BT}$ (%)')
    ax2b.set_ylabel('BSFC (g kWh$^{-1}$)')
    ax2.legend(handles=[lns1, lns2], loc='right', fontsize=8)
    _panel_label(ax2, '(b)')

    # Reference annotation at 85 % MCR
    eta85 = float(df.loc[np.isclose(df['Load_pct'], 85), 'eta_brake'].iloc[0]) * 100
    ax2.axvline(85, color='grey', lw=0.6, ls=':')
    ax2.annotate(f'85 % MCR\n$\\eta_{{BT}}$={eta85:.1f} %',
                 xy=(85, eta85), xytext=(70, eta85 - 3),
                 fontsize=8, color=color_eta,
                 arrowprops=dict(arrowstyle='->', color=color_eta, lw=0.8))

    _savefig(fig, 'fig01_energy_balance',
             'MAN B&W S65ME-C engine energy balance vs load')
    plt.close(fig)


