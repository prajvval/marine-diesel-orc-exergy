def _savefig(fig, stem, title):
    """Save PDF + PNG with provenance metadata."""
    meta = {'Title': title, 'Author': AUTHOR, 'CreationDate': NOW_STR}
    for ext, dpi in [('pdf', None), ('png', 600)]:
        path = os.path.join(FIGS, f'{stem}.{ext}')
        kw = dict(metadata=meta) if ext == 'pdf' else {}
        if dpi:
            kw['dpi'] = dpi
        fig.savefig(path, **kw)
    print(f'  saved  {stem}.pdf / .png')

def _panel_label(ax, label, x=0.03, y=0.97):
    """Place bold panel letter (a), (b), ... in top-left of axes area."""
    ax.text(x, y, label, transform=ax.transAxes,
            fontsize=10, fontweight='bold', fontfamily='DejaVu Sans',
            ha='left', va='top')

def _fluid_legend_handles(fluids):
    handles = []
    for f in fluids:
        c = FLUID_COLOR.get(f, FLUID_COLOR['default'])
        m = FLUID_MARKER.get(f, FLUID_MARKER['default'])
        handles.append(Line2D([0], [0], color=c, marker=m, ms=5,
                               lw=1.0, label=f))
    return handles

