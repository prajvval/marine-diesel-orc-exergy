def fig05_monte_carlo():
    mc  = pd.read_csv(os.path.join(RES, '05_monte_carlo_results.csv'))
    sen = pd.read_csv(os.path.join(RES, '05b_sensitivity_indices.csv'))

    fig, axes = plt.subplots(2, 2, figsize=(12, 9))
    fig.subplots_adjust(hspace=0.38, wspace=0.35)

    # (a) W_net histogram
    ax = axes[0, 0]
    mean_w  = mc['W_net_kW'].mean()
    lo95    = mc['W_net_kW'].quantile(0.025)
    hi95    = mc['W_net_kW'].quantile(0.975)
    ax.hist(mc['W_net_kW'], bins=70, color='#555555', alpha=0.75,
            edgecolor='none', density=False)
    ax.axvline(mean_w, color='#CC3311', lw=1.8, ls='-',
               label=f'Mean = {mean_w:.0f} kW')
    ax.axvline(lo95, color='#EE7733', lw=1.0, ls='--')
    ax.axvline(hi95, color='#EE7733', lw=1.0, ls='--',
               label=f'95 % CI [{lo95:.0f}, {hi95:.0f}] kW')
    ax.set_xlabel('Net ORC power (kW)')
    ax.set_ylabel('Count')
    ax.legend(fontsize=8)
    _panel_label(ax, '(a)')

    # (b) NPV histogram
    ax = axes[0, 1]
    npv_m = mc['NPV_20yr_USD'] / 1e6
    ax.hist(npv_m, bins=70, color='#0077BB', alpha=0.75, edgecolor='none')
    ax.axvline(0, color='#CC3311', lw=1.8, label='NPV = 0')
    pct_pos = (mc['NPV_20yr_USD'] > 0).mean() * 100
    ax.set_xlabel('20-year NPV (M USD)')
    ax.set_ylabel('Count')
    ax.legend(fontsize=8)
    ax.text(0.97, 0.90, f'{pct_pos:.0f} % positive',
            transform=ax.transAxes, ha='right', va='top', fontsize=8,
            color='#0077BB')
    _panel_label(ax, '(b)')

    # (c) Tornado chart
    ax = axes[1, 0]
    top = sen.nlargest(10, 'abs_correlation').sort_values('correlation_with_W_net')
    colors_t = ['#CC3311' if v < 0 else '#009988' for v in top['correlation_with_W_net']]
    ax.barh(range(len(top)), top['correlation_with_W_net'],
            color=colors_t, height=0.6, edgecolor='none')
    ax.set_yticks(range(len(top)))
    ax.set_yticklabels(top['parameter'].values, fontsize=8)
    ax.axvline(0, color='black', lw=0.6)
    ax.set_xlabel('Pearson correlation with $W_\\mathrm{net}$')
    _panel_label(ax, '(c)')

    # (d) W_net vs CO2, coloured by fuel price
    ax = axes[1, 1]
    sc = ax.scatter(mc['W_net_kW'], mc['co2_saved_tonnes'],
                    c=mc['fuel_price'], cmap='YlOrRd', alpha=0.25, s=4,
                    rasterized=True)
    cb = fig.colorbar(sc, ax=ax, shrink=0.85, pad=0.02)
    cb.set_label('Fuel price (USD/t)', fontsize=8)
    ax.set_xlabel('Net ORC power (kW)')
    ax.set_ylabel('Annual CO$_2$ saved (t yr$^{-1}$)')
    _panel_label(ax, '(d)')

    _savefig(fig, 'fig05_monte_carlo',
             f'Monte Carlo uncertainty analysis (N={len(mc):,})')
    plt.close(fig)


